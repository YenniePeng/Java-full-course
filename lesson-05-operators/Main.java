public class Main {
    public static void main(String[] args) {
        int x = 10;
        int y = 2;

        System.out.println("x + y = " + (x + y));
        System.out.println("x - y = " + (x - y));
        System.out.println("x * y = " + (x * y));
        System.out.println("x / y = " + (x / y));
        System.out.println("x % y = " + (x % y));

        int result = 3 + 4 * (8 - 6) / 2;
        System.out.println("3 + 4 * (8 - 6) / 2 = " + result);
    }
}
